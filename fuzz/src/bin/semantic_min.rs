//! A structure-aware crash-input minimiser for the fuzz targets — the
//! "semantic minimiser" half of issue #571 (XF-02), which named it
//! explicitly as the thing `cargo fuzz cmin`/`tmin` cannot do: "dropping an
//! entire box while fixing up parent lengths" (`planning/13-correctness.md`
//! §2.5.3).
//!
//! # Why this exists alongside `cargo fuzz tmin`
//!
//! `tmin` (and the byte-level ddmin this tool falls back to, see
//! [`byte_ddmin`]) only ever deletes contiguous byte ranges and checks
//! whether the input is still "interesting". For a length-prefixed
//! container format that is a slow way to shrink: deleting part of a box's
//! payload almost always makes the file corrupt in a way the *box header*
//! itself now disagrees with (the stated size no longer matches the actual
//! bytes), so the shrunk candidate is usually rejected even when the bug
//! has nothing to do with the deleted bytes — `tmin` recovers eventually by
//! deleting the header too, but pays for every byte along the way.
//!
//! This tool instead parses the container structure first (ISO base media
//! boxes or EBML elements — the two structured formats issue #571 names:
//! `mp4`/`isom_*` and `matroska`/`ebml_*`), and offers **whole boxes or
//! elements** as removal candidates, patching every ancestor's stored size
//! field by the removed length in the same edit. A crash that lives in one
//! `trak` of five, or one cluster of a hundred, shrinks in one step instead
//! of a byte-by-byte crawl. MPEG-TS needs no such parser: it is fixed
//! 188-byte packets with no length field to fix up, so whole-packet
//! deletion is just [`byte_ddmin`] run with a 188-byte-aligned first pass.
//!
//! Deliberately dependency-free (no `vaco-*` crate), matching
//! `diff_probe.rs`'s own reasoning in this same `fuzz/src/bin/` directory:
//! `fuzz/Cargo.toml` is entirely generated by `cargo xtask gen-fuzz` from
//! `fuzz_targets/*.rs` front-matter (see that file's header comment), so a
//! `src/bin/` tool that needs a real `vaco-format-isom`/`vaco-format-ebml`
//! path dependency would need a hand-edit that the next `gen-fuzz` run
//! silently erases — the generator only ever looks at `fuzz_targets/`.
//! Reimplementing the ~20 lines of box/VINT header parsing this needs is
//! far cheaper than teaching the generator about a second, differently
//! shaped kind of manifest entry that every other agent's `gen-fuzz` run
//! would then have to preserve.
//!
//! # What counts as "interesting"
//!
//! The oracle is the real fuzz target, replayed exactly the way
//! `fuzz/seeds/README.md` documents replaying a crash: `cargo +nightly fuzz
//! run <target> --no-default-features --features <feature> <file>`. A
//! non-zero exit is a reproduction. This is deliberately the same
//! subprocess-per-candidate cost `cargo fuzz tmin` itself pays — the
//! minimiser is meant to run once, by a human triaging one crash, not in a
//! fuzzing hot loop.
//!
//! # Usage
//!
//! ```text
//! cargo run --manifest-path fuzz/Cargo.toml --bin semantic_min -- \
//!     <target> <crash-file> [--out <path>] [--format mp4|ebml|ts|none]
//! ```
//!
//! `--format` is inferred from the target name when omitted (see
//! [`infer_format`]); pass it explicitly for a target this tool does not
//! recognise. The result — never longer than the input, and re-verified
//! against the oracle before being written — is printed to `--out`
//! (default: `<crash-file>.min`).

#![forbid(unsafe_code)]

use std::env;
use std::fmt;
use std::fs;
use std::path::{Path, PathBuf};
use std::process::{Command, ExitCode};

fn main() -> ExitCode {
    match run(env::args().skip(1).collect()) {
        Ok(()) => ExitCode::SUCCESS,
        Err(e) => {
            eprintln!("semantic_min: {e}");
            ExitCode::FAILURE
        }
    }
}

fn run(args: Vec<String>) -> Result<(), String> {
    let opts = Options::parse(&args)?;
    let original = fs::read(&opts.input)
        .map_err(|e| format!("reading {}: {e}", opts.input.display()))?;

    let fuzz_dir = fuzz_dir()?;
    let feature = opts
        .feature
        .clone()
        .or_else(|| required_feature(&fuzz_dir, &opts.target))
        .ok_or_else(|| {
            format!(
                "no `[[bin]] name = \"{}\"` with `required-features` found in \
                 fuzz/Cargo.toml — pass --feature explicitly",
                opts.target
            )
        })?;

    println!(
        "semantic_min: building {} (--features {feature})...",
        opts.target
    );
    build_target(&fuzz_dir, &opts.target, &feature)?;

    let calls = std::cell::Cell::new(0u64);
    let mut oracle = |data: &[u8]| -> bool {
        calls.set(calls.get() + 1);
        replay(&fuzz_dir, &opts.target, &feature, data).unwrap_or(false)
    };

    if !oracle(&original) {
        return Err(format!(
            "{} does not reproduce a crash in {} — nothing to minimise",
            opts.input.display(),
            opts.target
        ));
    }
    println!(
        "semantic_min: confirmed reproduction ({} bytes)",
        original.len()
    );

    let format = opts
        .format
        .unwrap_or_else(|| infer_format(&opts.target));
    println!("semantic_min: structural format = {format}");

    let mut data = original.clone();
    match format {
        Format::Mp4 => {
            data = structural_reduce(data, isom::parse, &mut oracle);
        }
        Format::Ebml => {
            data = structural_reduce(data, ebml::parse, &mut oracle);
        }
        Format::Ts => {
            data = packet_aligned_reduce(data, 188, &mut oracle);
        }
        Format::None => {}
    }
    println!(
        "semantic_min: after structural pass: {} bytes ({} oracle calls so far)",
        data.len(),
        calls.get()
    );

    data = byte_ddmin(data, &mut oracle, 200_000);
    println!(
        "semantic_min: after byte-level pass: {} bytes ({} oracle calls total)",
        data.len(),
        calls.get()
    );

    // Re-verify once more before writing: every accepted edit above was
    // itself oracle-checked, but a final check catches a logic error in the
    // reduction loops rather than trusting their bookkeeping.
    if !oracle(&data) {
        return Err(
            "internal error: the minimised output no longer reproduces — refusing to write it"
                .to_string(),
        );
    }

    let out = opts
        .out
        .clone()
        .unwrap_or_else(|| default_out_path(&opts.input));
    fs::write(&out, &data).map_err(|e| format!("writing {}: {e}", out.display()))?;
    println!(
        "semantic_min: {} -> {} ({} -> {} bytes, {:.1}% smaller) written to {}",
        opts.input.display(),
        out.display(),
        original.len(),
        data.len(),
        100.0 * (1.0 - data.len() as f64 / original.len().max(1) as f64),
        out.display()
    );
    Ok(())
}

// ------------------------------------------------------------------ options

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum Format {
    Mp4,
    Ebml,
    Ts,
    None,
}

impl fmt::Display for Format {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(match self {
            Format::Mp4 => "mp4",
            Format::Ebml => "ebml",
            Format::Ts => "ts",
            Format::None => "none",
        })
    }
}

struct Options {
    target: String,
    input: PathBuf,
    out: Option<PathBuf>,
    feature: Option<String>,
    format: Option<Format>,
}

impl Options {
    fn parse(args: &[String]) -> Result<Self, String> {
        let mut positional = Vec::new();
        let mut out = None;
        let mut feature = None;
        let mut format = None;
        let mut rest = args.iter();
        while let Some(arg) = rest.next() {
            match arg.as_str() {
                "--out" => {
                    out = Some(PathBuf::from(rest.next().ok_or("--out needs a path")?));
                }
                "--feature" => {
                    feature = Some(rest.next().ok_or("--feature needs a name")?.clone());
                }
                "--format" => {
                    format = Some(match rest.next().map(String::as_str) {
                        Some("mp4") => Format::Mp4,
                        Some("ebml") => Format::Ebml,
                        Some("ts") => Format::Ts,
                        Some("none") => Format::None,
                        other => {
                            return Err(format!(
                                "--format wants mp4|ebml|ts|none, got {other:?}"
                            ));
                        }
                    });
                }
                other => positional.push(other.to_string()),
            }
        }
        let usage = "usage: semantic_min <target> <crash-file> [--out PATH] \
                      [--feature NAME] [--format mp4|ebml|ts|none]";
        let mut positional = positional.into_iter();
        let target = positional.next().ok_or(usage)?;
        let input = positional.next().ok_or(usage)?;
        if positional.next().is_some() {
            return Err(usage.to_string());
        }
        Ok(Self {
            target,
            input: PathBuf::from(input),
            out,
            feature,
            format,
        })
    }
}

fn default_out_path(input: &Path) -> PathBuf {
    let mut s = input.as_os_str().to_owned();
    s.push(".min");
    PathBuf::from(s)
}

/// Guess a target's structural format from its name. Every target this
/// tool can help with names its format in its own name already
/// (`dem_mp4`/`isom_*`, `matroska_*`/`ebml_*`, `mpegts_*`), which is the
/// same convention `fuzz-feature`/`fuzz-all` in the `Justfile` rely on to
/// find a target's feature.
fn infer_format(target: &str) -> Format {
    if target.contains("mp4") || target.starts_with("isom") {
        Format::Mp4
    } else if target.contains("matroska") || target.contains("ebml") {
        Format::Ebml
    } else if target.contains("mpegts") {
        Format::Ts
    } else {
        Format::None
    }
}

// -------------------------------------------------------------- fuzz plumbing

fn fuzz_dir() -> Result<PathBuf, String> {
    // This binary is itself built from `fuzz/Cargo.toml`, so `CARGO_MANIFEST_DIR`
    // at build time is exactly the directory every `cargo +nightly fuzz` command
    // below must run from.
    env::var("CARGO_MANIFEST_DIR")
        .map(PathBuf::from)
        .or_else(|_| env::current_dir().map_err(|e| e.to_string()))
}

/// Reimplements the `Justfile`'s private `fuzz-feature` recipe: read the
/// `required-features` of the `[[bin]] name = "<target>"` entry
/// `gen-fuzz` wrote into `fuzz/Cargo.toml`.
fn required_feature(fuzz_dir: &Path, target: &str) -> Option<String> {
    let manifest = fs::read_to_string(fuzz_dir.join("Cargo.toml")).ok()?;
    let needle = format!("name = \"{target}\"");
    let start = manifest.find(&needle)?;
    let block = manifest.get(start..)?;
    let block = block.get(..block.find("[[bin]]").unwrap_or(block.len()))?;
    let line = block
        .lines()
        .find(|l| l.trim_start().starts_with("required-features"))?;
    let (_, rest) = line.split_once('[')?;
    let (name, _) = rest.split_once(']')?;
    Some(name.trim().trim_matches('"').to_string())
}

fn build_target(fuzz_dir: &Path, target: &str, feature: &str) -> Result<(), String> {
    let status = Command::new("cargo")
        .current_dir(fuzz_dir)
        .args([
            "+nightly",
            "fuzz",
            "build",
            target,
            "--no-default-features",
            "--features",
            feature,
        ])
        .status()
        .map_err(|e| format!("spawning cargo +nightly fuzz build: {e}"))?;
    if !status.success() {
        return Err(format!("cargo +nightly fuzz build {target} failed"));
    }
    Ok(())
}

/// Run one replay, exactly the command `fuzz/seeds/README.md` documents.
/// `Ok(true)` means the target crashed on `data` (a reproduction); `Ok(false)`
/// means it ran clean.
fn replay(fuzz_dir: &Path, target: &str, feature: &str, data: &[u8]) -> Result<bool, String> {
    let tmp = fuzz_dir.join(format!(".semantic_min-{}.tmp", std::process::id()));
    fs::write(&tmp, data).map_err(|e| format!("writing scratch input: {e}"))?;
    let status = Command::new("cargo")
        .current_dir(fuzz_dir)
        .args([
            "+nightly",
            "fuzz",
            "run",
            target,
            "--no-default-features",
            "--features",
            feature,
        ])
        .arg(&tmp)
        .stdout(std::process::Stdio::null())
        .stderr(std::process::Stdio::null())
        .status()
        .map_err(|e| format!("spawning cargo +nightly fuzz run: {e}"));
    let _ = fs::remove_file(&tmp);
    Ok(!status?.success())
}

// -------------------------------------------------------- structural reducer

/// A removable byte range plus the ancestor size fields that must be
/// decremented if it is removed.
struct Candidate {
    start: usize,
    end: usize,
    /// `(byte offset of the size field, width)` for every ancestor whose
    /// stored size includes this range and is not "extends to end of
    /// container" (which needs no stored value to correct).
    patches: Vec<SizeField>,
}

#[derive(Clone, Copy)]
enum SizeField {
    /// A big-endian integer of `width` bytes at `offset`.
    BigEndian { offset: usize, width: u8 },
    /// An EBML size VINT at `offset` spanning `width` bytes, whose top
    /// `width` marker bit must be preserved (keeping the same encoded
    /// width, per RFC 8794 §4 — a value never has to grow past what it
    /// already fit, since it only ever shrinks here).
    EbmlVint { offset: usize, width: u8 },
}

fn apply_patches(buf: &mut [u8], patches: &[SizeField], delta: u64) {
    for patch in patches {
        match *patch {
            SizeField::BigEndian { offset, width } => {
                let width = width as usize;
                let Some(slice) = buf.get_mut(offset..offset.saturating_add(width)) else {
                    continue;
                };
                let mut value: u64 = 0;
                for &b in slice.iter() {
                    value = (value << 8) | u64::from(b);
                }
                value = value.saturating_sub(delta);
                for (i, b) in slice.iter_mut().enumerate() {
                    let shift = 8 * (width - 1 - i);
                    *b = ((value >> shift) & 0xFF) as u8;
                }
            }
            SizeField::EbmlVint { offset, width } => {
                let width = width as usize;
                let Some(slice) = buf.get_mut(offset..offset.saturating_add(width)) else {
                    continue;
                };
                // Decode: byte 0 contributes its low `8 - width` bits (the
                // marker occupies the high `width` bits), every later byte
                // contributes all 8 — RFC 8794 §4's VINT_DATA, MSB first.
                let mut value: u64 = 0;
                for (i, &b) in slice.iter().enumerate() {
                    if i == 0 {
                        let payload_mask = (1u16 << (8 - width)) as u8 - 1;
                        value = u64::from(b & payload_mask);
                    } else {
                        value = (value << 8) | u64::from(b);
                    }
                }
                // Only ever shrinks (a removal never adds bytes), so the new
                // value still fits in the same `7 * width` data bits the
                // original one did — the width itself never has to change.
                value = value.saturating_sub(delta);
                // Re-encode at the same width: byte 0 = marker | the value's
                // top `8 - width` bits, every later byte = the next 8 bits
                // down, standard big-endian.
                let marker = 1u8 << (8 - width);
                if let Some(first) = slice.first_mut() {
                    let high = if width > 1 {
                        (value >> (8 * (width - 1))) as u8
                    } else {
                        value as u8
                    };
                    *first = marker | (high & marker.wrapping_sub(1));
                }
                for i in 1..width {
                    let shift = 8 * (width - 1 - i);
                    if let Some(b) = slice.get_mut(i) {
                        *b = (value >> shift) as u8;
                    }
                }
            }
        }
    }
}

/// Remove `[c.start, c.end)` from `buf`, first patching every ancestor size
/// field by the removed length.
fn remove_candidate(buf: &[u8], c: &Candidate) -> Vec<u8> {
    let delta = (c.end - c.start) as u64;
    let mut patched = buf.to_vec();
    apply_patches(&mut patched, &c.patches, delta);
    let mut out = Vec::new();
    out.extend_from_slice(patched.get(..c.start).unwrap_or_default());
    out.extend_from_slice(patched.get(c.end..).unwrap_or_default());
    out
}

/// A single parsed container node: its own extent, whether it has a size
/// field a removal must patch, and its children (already offset-absolute).
struct Node {
    start: usize,
    end: usize,
    /// `None` for the synthetic root (the whole buffer) and for a
    /// "to end of container"/"unknown size" node — nothing stored to fix up.
    size_field: Option<SizeField>,
    children: Vec<Node>,
}

fn flatten_candidates(root: &Node) -> Vec<Candidate> {
    let mut out = Vec::new();
    fn walk(node: &Node, ancestors: &[SizeField], out: &mut Vec<Candidate>) {
        for child in &node.children {
            out.push(Candidate {
                start: child.start,
                end: child.end,
                patches: ancestors.to_vec(),
            });
            let mut next = ancestors.to_vec();
            if let Some(f) = child.size_field {
                next.push(f);
            }
            walk(child, &next, out);
        }
    }
    walk(root, &[], &mut out);
    out
}

/// Repeatedly remove the largest structural node that keeps the oracle
/// interesting, re-parsing after every accepted edit (offsets shift), until
/// no single removal helps.
fn structural_reduce(
    mut buf: Vec<u8>,
    parse: fn(&[u8]) -> Node,
    oracle: &mut impl FnMut(&[u8]) -> bool,
) -> Vec<u8> {
    loop {
        let root = parse(&buf);
        let mut candidates = flatten_candidates(&root);
        candidates.sort_by_key(|c| std::cmp::Reverse(c.end - c.start));
        let mut reduced = false;
        for c in &candidates {
            if c.end <= c.start {
                continue;
            }
            let candidate = remove_candidate(&buf, c);
            if oracle(&candidate) {
                buf = candidate;
                reduced = true;
                break;
            }
        }
        if !reduced {
            return buf;
        }
    }
}

/// MPEG-TS has no length-prefixed structure to fix up — packets are a fixed
/// 188 bytes — so "structural" here just means the byte-level algorithm's
/// first pass is aligned to the packet size, which converges in one pass
/// for a bug that only needs N packets instead of the file's original count.
fn packet_aligned_reduce(
    mut buf: Vec<u8>,
    packet: usize,
    oracle: &mut impl FnMut(&[u8]) -> bool,
) -> Vec<u8> {
    loop {
        let mut reduced = false;
        let packets = buf.len() / packet;
        for i in (0..packets).rev() {
            let start = i * packet;
            let end = start + packet;
            let mut candidate = buf.clone();
            candidate.drain(start..end);
            if oracle(&candidate) {
                buf = candidate;
                reduced = true;
            }
        }
        if !reduced {
            return buf;
        }
    }
}

/// Classic delta-debugging (Zeller & Hildebrandt): shrink by removing
/// ever-smaller chunks while `oracle` still reports the input interesting.
/// Same algorithm `vaco-corpus::mutate::minimise` implements for the
/// differential harness's own crash minimisation; reimplemented here
/// (rather than depended on) for the reason this file's module doc gives —
/// `fuzz/Cargo.toml` cannot carry a hand-added path dependency.
fn byte_ddmin(mut data: Vec<u8>, oracle: &mut impl FnMut(&[u8]) -> bool, max_iters: usize) -> Vec<u8> {
    if data.len() < 2 {
        return data;
    }
    let mut chunk = data.len().div_ceil(2).max(1);
    let mut iters = 0usize;
    while chunk >= 1 {
        let mut start = 0usize;
        let mut shrank_this_pass = false;
        while start < data.len() {
            let end = (start + chunk).min(data.len());
            let mut candidate = data.clone();
            candidate.drain(start..end);
            iters += 1;
            if !candidate.is_empty() && oracle(&candidate) {
                data = candidate;
                shrank_this_pass = true;
                // Retry at the same offset against the now-shorter buffer.
            } else {
                start = end;
            }
            if iters >= max_iters {
                return data;
            }
        }
        if chunk == 1 && !shrank_this_pass {
            break;
        }
        chunk = if shrank_this_pass { chunk } else { chunk.div_ceil(2) };
        if chunk == 0 {
            break;
        }
    }
    data
}

// -------------------------------------------------------------------- isom

mod isom {
    use super::{Node, SizeField};

    const HEADER_LEN: usize = 8;
    const LARGESIZE_HEADER_LEN: usize = 16;

    /// Parse ISO base media boxes (ISO/IEC 14496-12 §4.2) starting at
    /// `base` inside `buf`, treating `[base, end)` as one container. Never
    /// panics: any header that doesn't fit or claims an impossible size
    /// just stops the walk there, which is always safe for a minimiser —
    /// a wrongly-stopped walk only means fewer removal candidates, never
    /// an incorrect one, since [`super::remove_candidate`] always re-checks
    /// the oracle before accepting an edit.
    fn parse_container(buf: &[u8], base: usize, end: usize) -> Vec<Node> {
        let mut out = Vec::new();
        let mut at = base;
        let mut guard = 0usize;
        while at.saturating_add(HEADER_LEN) <= end {
            guard += 1;
            if guard > 1 << 20 {
                break;
            }
            let Some(header) = buf.get(at..at.saturating_add(4)) else {
                break;
            };
            let Ok(header): Result<[u8; 4], _> = header.try_into() else {
                break;
            };
            let size32 = u32::from_be_bytes(header) as u64;
            let (total, header_len, size_field) = if size32 == 1 {
                let Some(large) = buf.get(at.saturating_add(8)..at.saturating_add(16)) else {
                    break;
                };
                let Ok(b): Result<[u8; 8], _> = large.try_into() else {
                    break;
                };
                (
                    u64::from_be_bytes(b),
                    LARGESIZE_HEADER_LEN,
                    Some(SizeField::BigEndian {
                        offset: at.saturating_add(8),
                        width: 8,
                    }),
                )
            } else if size32 == 0 {
                // Extends to the end of this container: nothing stored to patch.
                (
                    (end.saturating_sub(at)) as u64,
                    HEADER_LEN,
                    None,
                )
            } else {
                (
                    size32,
                    HEADER_LEN,
                    Some(SizeField::BigEndian { offset: at, width: 4 }),
                )
            };
            if total < header_len as u64 {
                break;
            }
            let box_end = match at.checked_add(usize::try_from(total).unwrap_or(usize::MAX)) {
                Some(v) if v <= end => v,
                _ => break,
            };
            let children = parse_container(buf, at.saturating_add(header_len), box_end);
            out.push(Node {
                start: at,
                end: box_end,
                size_field,
                children,
            });
            if box_end <= at {
                break;
            }
            at = box_end;
        }
        out
    }

    pub fn parse(buf: &[u8]) -> Node {
        Node {
            start: 0,
            end: buf.len(),
            size_field: None,
            children: parse_container(buf, 0, buf.len()),
        }
    }
}

// -------------------------------------------------------------------- ebml

mod ebml {
    use super::{Node, SizeField};

    /// Read an EBML VINT (ID or size) starting at `at`. Returns
    /// `(value_with_marker_stripped, byte_width, is_all_ones)` — the last
    /// flag is how both the ID space and the size space spell "unknown"
    /// (RFC 8794 §4, §6.1/6.2): a size VINT whose payload bits are all 1
    /// means "extends to whichever ancestor's bounds end it", so it is
    /// treated exactly like ISOBMFF's `size == 0`, with no field to patch.
    fn read_vint(buf: &[u8], at: usize) -> Option<(u64, usize, bool)> {
        let first = *buf.get(at)?;
        if first == 0 {
            return None;
        }
        let width = first.leading_zeros() as usize + 1;
        if width > 8 {
            return None;
        }
        let bytes = buf.get(at..at.checked_add(width)?)?;
        // Payload bits available in byte 0: `8 - width` (the top `width`
        // bits are the leading zeros plus the marker bit). For `width == 8`
        // that is 0 — an 8-byte VINT's first byte is marker only, and every
        // data bit lives in the remaining 7 bytes.
        let mask = (!(0xFFu16 << (8 - width))) as u8;
        let mut value = u64::from(bytes.first().copied().unwrap_or(0) & mask);
        let mut all_ones = value == u64::from(mask);
        for &b in bytes.get(1..).unwrap_or_default() {
            value = (value << 8) | u64::from(b);
            all_ones &= b == 0xFF;
        }
        Some((value, width, all_ones))
    }

    fn parse_container(buf: &[u8], base: usize, end: usize) -> Vec<Node> {
        let mut out = Vec::new();
        let mut at = base;
        let mut guard = 0usize;
        while at < end {
            guard += 1;
            if guard > 1 << 20 {
                break;
            }
            let Some((_, id_width, _)) = read_vint(buf, at) else {
                break;
            };
            let size_offset = at.saturating_add(id_width);
            let Some((size_value, size_width, unknown)) = read_vint(buf, size_offset) else {
                break;
            };
            let header_len = id_width + size_width;
            let (total, size_field) = if unknown {
                (end.saturating_sub(at) as u64, None)
            } else {
                (
                    (header_len as u64).saturating_add(size_value),
                    Some(SizeField::EbmlVint {
                        offset: size_offset,
                        width: size_width as u8,
                    }),
                )
            };
            let elem_end = match at.checked_add(usize::try_from(total).unwrap_or(usize::MAX)) {
                Some(v) if v <= end && v > at => v,
                _ => break,
            };
            let children = parse_container(buf, at.saturating_add(header_len), elem_end);
            out.push(Node {
                start: at,
                end: elem_end,
                size_field,
                children,
            });
            at = elem_end;
        }
        out
    }

    pub fn parse(buf: &[u8]) -> Node {
        Node {
            start: 0,
            end: buf.len(),
            size_field: None,
            children: parse_container(buf, 0, buf.len()),
        }
    }
}

