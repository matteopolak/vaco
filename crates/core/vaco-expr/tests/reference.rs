//! Differential vectors captured from the reference binary.
//!
//! Every row is an expression paired with the exact f64 bit pattern the
//! reference produced, or `None` where it rejected the expression. They were
//! captured with the probe harness documented in `docs/core/vaco-expr.md`:
//!
//! ```text
//! ffmpeg -hide_banner -loglevel error -f lavfi \
//!        -i "aevalsrc=exprs='<expr>':s=1:n=1:d=1" -f f64le -
//! ```
//!
//! `aevalsrc` writes the expression's value straight into a `dbl` sample, so
//! `-f f64le` hands back the raw 64 bits with nothing rounded or formatted in
//! between. That is what makes these vectors bit-exact rather than
//! approximate, and it is why this file compares bit patterns and not values —
//! `0.1` printed to 17 digits would hide a one-ULP disagreement.
//!
//! Captured against `ffmpeg version 8.1` on `aarch64-apple-darwin`.
//!
//! The probe command binds `aevalsrc`'s own three variables, so the vectors
//! exercise variable resolution too: `n` = 0 (first sample), `t` = 0 (first
//! sample) and `s` = 1 (`s=1` in the command above).
//!
//! Two families are excluded deliberately: anything calling `time` (not
//! reproducible) and anything calling `random`/`randomi` (a known divergence,
//! recorded in the crate docs).

