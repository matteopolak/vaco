/// The variables `aevalsrc` exposes, in the order the vectors assume.
const VAR_NAMES: &[&str] = &["n", "t", "s"];
/// Their values for the first sample of the probe command (`s=1:n=1:d=1`).
const VAR_VALUES: &[f64] = &[0.0, 0.0, 1.0];

/// Expressions where we knowingly differ, each with the reason.
///
/// Keeping them in the corpus but naming them here is deliberate: a silent
/// deletion would make the divergence invisible, and a plain `assert` would
/// make the whole suite red for something already decided.
const KNOWN_DIVERGENCES: &[(&str, &str)] = &[(
    "root(cos(ld(0)),10)",
    "the reference constrains the secant iterate once the endpoints bracket a \
     sign change; the rule could not be established by black-box probing, so a \
     plain secant wanders off where the reference converges on 5*PI/2",
)];

#[test]
fn matches_reference_bit_for_bit() {
    let bindings = Bindings::new(VAR_NAMES);
    let mut failures = Vec::new();
    for (src, expected) in VECTORS {
        if KNOWN_DIVERGENCES.iter().any(|(s, _)| s == src) {
            continue;
        }
        let parsed = Expr::parse(src, &bindings);
        match (parsed, expected) {
            (Err(_), None) => {}
            (Ok(e), Some(bits)) => {
                let got = e.eval(VAR_VALUES).to_bits();
                // NaN sign and payload are compared leniently. `mod(0,0)` comes
                // back as -NaN from the reference and +NaN from us: the C
                // compiler contracted `x - y*floor(x/y)` into an `fmsub`, whose
                // operand negation flips the sign bit of a propagated NaN,
                // while Rust does not enable FP contraction. No user-facing
                // output path can observe a NaN's sign bit, so this is a
                // codegen artefact rather than a behavioural difference.
                let both_nan = f64::from_bits(got).is_nan() && f64::from_bits(*bits).is_nan();
                if got != *bits && !both_nan {
                    failures.push(format!("{src:?}: got {got:#018x}, reference {bits:#018x}"));
                }
            }
            (Ok(e), None) => {
                let v = e.eval(VAR_VALUES);
                failures.push(format!("{src:?}: we accept it ({v}), reference rejects"));
            }
            (Err(err), Some(bits)) => {
                failures.push(format!(
                    "{src:?}: we reject it ({err}), reference gives {bits:#018x}"
                ));
            }
        }
    }
    assert!(
        failures.is_empty(),
        "{} of {} vectors disagree:\n{}",
        failures.len(),
        VECTORS.len(),
        failures.join("\n")
    );
}

#[test]
fn corpus_is_big_enough_to_mean_something() {
    // A guard against this file being silently emptied: if the vectors ever
    // stop being generated, the test above passes vacuously.
    assert!(VECTORS.len() > 300, "corpus shrank to {}", VECTORS.len());
    let rejected = VECTORS.iter().filter(|(_, b)| b.is_none()).count();
    assert!(rejected > 50, "only {rejected} rejection vectors");
    for (src, _) in KNOWN_DIVERGENCES {
        assert!(
            VECTORS.iter().any(|(s, _)| s == src),
            "{src:?} is listed as a known divergence but is not in the corpus"
        );
    }
}
