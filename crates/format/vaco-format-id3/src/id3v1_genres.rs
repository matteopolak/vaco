//! The 192-entry `ID3v1` genre table.
//!
//! Obtained by direct measurement, not transcription: a synthetic `ID3v1` tag
//! was built for every byte value `0..=255` and read back with `ffprobe -v
//! quiet -show_entries format_tags=genre -of default=nw=1:nk=1`. Values
//! `0..=191` each produced exactly one name; `192..=255` produced no
//! `genre` tag at all (confirmed at `200` and at the conventional
//! "unspecified" sentinel `255`), which is why this table stops at 191 and
//! [`crate::id3v1::genre_name`] returns `None` above it rather than padding
//! the array out to 256 entries with a guess.
//!
