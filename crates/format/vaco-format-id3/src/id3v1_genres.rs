    fn spot_check_a_few_probed_values() {
        assert_eq!(ID3V1_GENRES[0], "Blues");
        assert_eq!(ID3V1_GENRES[17], "Rock");
        assert_eq!(ID3V1_GENRES[79], "Hard Rock");
        assert_eq!(ID3V1_GENRES[191], "Psybient");
    }
