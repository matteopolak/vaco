//! The local-tag dictionary: which [`Ul`] each structural-metadata property
//! resolves to, once its set's local tag has been looked up in the primer.
//!
//! # Why match by UL and not by raw tag number
//!
//! A primer pack exists precisely because a local tag's meaning is **per
//! file**: two files are free to assign `0x3c0a` to different properties, as
//! long as each carries a primer pack saying so. Every real writer assigns
//! the RP210 baseline tags conventionally (`0x3c0a` is `InstanceUID`
//! everywhere in practice), but matching the *resolved UL* rather than the
//! raw tag is what makes that a convention this crate can rely on rather
//! than an assumption it is silently making — a file with a hostile or
//! merely unusual primer still gets read correctly, or its properties are
//! correctly left unrecognised, instead of being misattributed.
//!
//! # Source
//!
//! SMPTE RP 210 (the metadata dictionary) registers every property UL below.
//! Each was **measured**, not transcribed from a table: decoded from a real
//! primer pack and the local-set items it unlocks, in a file `ffmpeg 8.1`
//! wrote (`ffmpeg -f lavfi -i testsrc=... -f mxf out.mxf`), per D6/D17. That
//! is why `method = "probed"` in `provenance/vaco-demux-mxf.toml` even
//! though the underlying document is a spec: the *transcription route* was
//! a real file's bytes, not the RP210 text, and recording that honestly is
//! the whole point of the provenance record (see `docs/provenance.md`,
//! "Two fields answer two different questions").

