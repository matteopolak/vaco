/// A tag-to-property resolver, built once per file from its primer pack.
#[derive(Debug)]
pub struct Resolver {
    /// UL -> property, built once from [`TABLE`] (a `match` over 40+ arms
    /// would be equivalent; a map reads better at the call site and is built
    /// exactly once per open file).
    by_ul: HashMap<[u8; 16], PropertyId>,
}

impl Resolver {
    #[must_use]
    pub fn new() -> Self {
        Self {
            by_ul: TABLE.iter().map(|&(p, ul)| (ul.as_bytes(), p)).collect(),
        }
    }

    /// Resolve a local tag through `primer`, then through the property
    /// table. `None` for a tag the primer does not know, or whose UL this
    /// crate does not interpret — both are "leave the raw bytes visible on
    /// the set, do not fail the parse" cases at the call site.
    #[must_use]
    pub fn resolve(&self, primer: &HashMap<u16, Ul>, tag: u16) -> Option<PropertyId> {
        let ul = primer.get(&tag)?;
        self.by_ul.get(&ul.as_bytes()).copied()
    }
}

impl Default for Resolver {
    fn default() -> Self {
        Self::new()
    }
}

#[cfg(test)]
#[allow(clippy::unwrap_used, reason = "test code")]
mod tests {
    use super::*;

    #[test]
    fn instance_uid_tag_resolves_through_a_measured_primer_entry() {
        let mut primer = HashMap::new();
        primer.insert(
            0x3c0a,
            Ul::new([
                0x06, 0x0e, 0x2b, 0x34, 0x01, 0x01, 0x01, 0x01, 0x01, 0x01, 0x15, 0x02, 0x00, 0x00,
                0x00, 0x00,
            ]),
        );
        let r = Resolver::new();
        assert_eq!(r.resolve(&primer, 0x3c0a), Some(PropertyId::InstanceUid));
    }

    #[test]
    fn an_unregistered_tag_resolves_to_nothing() {
        let primer = HashMap::new();
        let r = Resolver::new();
        assert_eq!(r.resolve(&primer, 0x3c0a), None);
    }

    #[test]
    fn a_primer_that_lies_about_a_tag_is_not_misinterpreted() {
        // A hostile or merely unusual primer maps 0x3c0a to something this
        // crate does not recognise as InstanceUID. Matching by UL (not by
        // raw tag) means this resolves to nothing, not to the wrong
        // property.
        let mut primer = HashMap::new();
        primer.insert(0x3c0a, Ul::new([0xAA; 16]));
        let r = Resolver::new();
        assert_eq!(r.resolve(&primer, 0x3c0a), None);
    }
}
