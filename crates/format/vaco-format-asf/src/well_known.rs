/// The spec name for a well-known GUID, or `None` for a vendor/private one.
#[must_use]
pub fn name_of(guid: Guid) -> Option<&'static str> {
    ALL.iter().find(|(g, _)| *g == guid).map(|(_, n)| *n)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn header_and_data_object_share_the_same_first_bytes() {
        // Both are `75B22636...`/`75B22630...`: transcribed correctly if only
        // the last byte of Data1 differs.
        assert_ne!(HEADER_OBJECT, DATA_OBJECT);
        assert_eq!(HEADER_OBJECT.as_bytes()[1..], DATA_OBJECT.as_bytes()[1..]);
    }

    #[test]
    fn name_of_finds_every_table_entry() {
        for &(g, n) in ALL {
            assert_eq!(name_of(g), Some(n));
        }
        assert_eq!(name_of(Guid::from_bytes([0xAB; 16])), None);
    }

    #[test]
    fn audio_and_video_media_guids_match_the_spec_text() {
        assert_eq!(
            AUDIO_MEDIA.to_string(),
            "F8699E40-5B4D-11CF-A8FD-00805F5C442B"
        );
        assert_eq!(
            VIDEO_MEDIA.to_string(),
            "BC19EFC0-5B4D-11CF-A8FD-00805F5C442B"
        );
    }
}
