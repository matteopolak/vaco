//! The standard ASF GUIDs, transcribed from [\[ASF\] §10](crate) (revision
//! 01.20.06) — top-level object types, Header Object children, stream types,
//! and error-correction types.
//!
//! Every value here was typed in from the specification's own GUID tables,
//! not from any implementation's header file (D7/D15): see
//! `docs/format/vaco-format-asf.md` for the exact source used to fetch the
//! text of the specification. [`Guid::from_fields`] takes the four dashed
//! groups exactly as the spec prints them, so each entry below is a direct
//! transcription with nothing to get backwards.

use crate::guid::Guid;

macro_rules! guid_table {
    ($($konst:ident, $name:literal = $d1:literal, $d2:literal, $d3:literal, [$($d4:literal),+ $(,)?];)+) => {
        $(
            #[doc = concat!("`", $name, "`.")]
            pub const $konst: Guid = Guid::from_fields($d1, $d2, $d3, [$($d4),+]);
        )+

        /// Every constant in this module, paired with its spec name — the
        /// table [`name_of`] and the fuzz/debug `Display` impl walk.
        pub const ALL: &[(Guid, &str)] = &[
            $(($konst, $name),)+
        ];
    };
}

