//! An embedded fixed-width 8x8 bitmap font, for the "scope" filters that
//! draw digits and labels directly into a frame (`datascope`,
//! `graphmonitor`/`agraphmonitor`, and if shipped, `pixscope`/
//! `oscilloscope`).
//!
//! # Why this exists, and why it is not the reference's font
//!
//! The reference's own `datascope`/`pixscope`/`oscilloscope` draw text with
//! an embedded fixed-width bitmap font: `ffmpeg -h filter=datascope` (and
//! `pixscope`, `oscilloscope`) exposes no font/fontfile/fontsize option at
//! all, and the rendered output (measured directly: an all-black and an
//! all-white `32x32` `gray` source through
//! `datascope=s=64x32:mode=mono:format=hex`, pixel-dumped) is crisp,
//! non-antialiased, laid out on an exact 8-pixel horizontal grid pitch —
//! the signature of a compiled-in bitmap glyph table blitted directly,
//! not a scalable/shaped font. `pixscope`'s statistics overlay was checked
//! the same way and uses visually the same glyph family. This is a much
//! smaller prerequisite than `vaco-filter-text`'s planned `TextRenderer`
//! (fontdb, shaping, glyph cache — GitHub `FT-3.5`/#462), and does not
//! touch that issue's blocked `rustybuzz` provenance question at all: no
//! shaping, no font file, nothing but a lookup table and a blit.
//!
//! A bitmap font's glyph table is itself authorial data (D7): the
//! reference's own table cannot be transcribed into this tree. The glyphs
//! below are transcribed instead from Unscii, an independent, unrelated,
//! Public Domain bitmap font project (`unscii-8.hex`, the plain 8x8
//! variant — not the GPL Unifont-derived `-full` variant). Its glyph
//! shapes visually differ from the reference's own font wherever the two
//! were compared in this crate's measurements (its `'0'` has a different
//! stroke gap than the reference's), which is expected and desired: it
//! confirms this is a different, independently-sourced table, not a
//! disguised transcription of the one this tree is forbidden to read.
//! Registered as source `unscii-8-font` in `provenance/sources.toml` and
//! as a `[[table]]` entry in `provenance/vaco-filter-scope.toml`.
//!
//! One direct, permanent consequence: because the glyph shapes differ from
//! the reference's own font, no frame this font draws text into can ever
//! be framecrc-identical to the reference's output, even once every other
//! part of a filter's algorithm is measured exactly. That is a structural
//! ceiling, not a bug — the same kind of permanent, by-design exclusion
//! this crate's `hqx`-style D7 calls already document elsewhere in this
//! tree, just for a "verifiable at all" axis (pixel value, cell position)
//! rather than an "implementable at all" one.
//!
//! # Layout
//!
//! 95 glyphs, ASCII `0x20` (space) through `0x7E` (`~`), each 8 rows of 8
//! bits, most-significant bit leftmost. [`glyph`] indexes by ASCII byte and
//! falls back to the blank space glyph for anything outside that range or
//! not present (there is no such gap in `0x20..=0x7E`, but a filter reading
//! attacker-influenced bytes — none currently does — must not panic on one).

