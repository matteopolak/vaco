/// Look up one ASCII byte's glyph bitmap. Out-of-range bytes get the blank
/// (space) glyph rather than panicking.
#[must_use]
pub(crate) fn glyph(ch: u8) -> [u8; 8] {
    if !(FIRST..=LAST).contains(&ch) {
        return GLYPHS[0];
    }
    GLYPHS
        .get(usize::from(ch - FIRST))
        .copied()
        .unwrap_or(GLYPHS[0])
}

/// Whether row `row`, column `col` (both `0..8`) of `ch`'s glyph is "on".
#[must_use]
pub(crate) fn glyph_pixel(ch: u8, row: usize, col: usize) -> bool {
    let g = glyph(ch);
    let Some(&byte) = g.get(row) else {
        return false;
    };
    if col >= 8 {
        return false;
    }
    // MSB-first: column 0 is bit 7.
    (byte >> (7 - col)) & 1 != 0
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Pinned against `unscii-8.hex`'s own line for U+0030: `3C666E7666663C00`.
    #[test]
    fn digit_zero_matches_the_transcribed_source_bytes() {
        assert_eq!(
            glyph(b'0'),
            [0x3C, 0x66, 0x6E, 0x76, 0x66, 0x66, 0x3C, 0x00]
        );
    }

    /// Pinned against `unscii-8.hex`'s own line for U+0041: `183C66667E666600`.
    #[test]
    fn letter_a_matches_the_transcribed_source_bytes() {
        assert_eq!(
            glyph(b'A'),
            [0x18, 0x3C, 0x66, 0x66, 0x7E, 0x66, 0x66, 0x00]
        );
    }

    #[test]
    fn space_is_blank() {
        assert_eq!(glyph(b' '), [0u8; 8]);
        for row in 0..8 {
            for col in 0..8 {
                assert!(!glyph_pixel(b' ', row, col));
            }
        }
    }

    #[test]
    fn out_of_range_bytes_fall_back_to_the_blank_glyph_rather_than_panicking() {
        assert_eq!(glyph(0x00), glyph(b' '));
        assert_eq!(glyph(0xFF), glyph(b' '));
    }

    #[test]
    fn glyph_pixel_decodes_msb_first() {
        // '!' (U+0021) is `183C3C3C1800180000` in the 16x16... no: it's 8
        // bytes for unscii-8: 18 18 18 18 18 00 18 00 (a vertical bar with a
        // gap then a dot), each byte high bit at column 0.
        let bang = glyph(b'!');
        assert_eq!(bang, [0x18, 0x18, 0x18, 0x18, 0x18, 0x00, 0x18, 0x00]);
        // 0x18 = 0b00011000: MSB-first, so bit 7 is column 0 — columns 3
        // and 4 are on (bits 4 and 3), the rest off.
        assert!(!glyph_pixel(b'!', 0, 0));
        assert!(!glyph_pixel(b'!', 0, 1));
        assert!(!glyph_pixel(b'!', 0, 2));
        assert!(glyph_pixel(b'!', 0, 3));
        assert!(glyph_pixel(b'!', 0, 4));
        assert!(!glyph_pixel(b'!', 0, 5));
    }
}
