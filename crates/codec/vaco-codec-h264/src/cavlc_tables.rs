/// `nC >= 8`: fixed-length, clause 9.2.1's rule rather than a table.
///
/// `total_coeff == 0` is the single irregular code (`0b000011`, 6 bits);
/// otherwise the 6-bit code is `(total_coeff - 1) * 4 + trailing_ones`.
#[must_use]
#[cfg(test)]
pub(crate) const fn coeff_token_fixed_length(total_coeff: u8, trailing_ones: u8) -> (u8, u16) {
    if total_coeff == 0 {
        (6, 0b000011)
    } else {
        (6, ((total_coeff as u16 - 1) * 4) + trailing_ones as u16)
    }
}

