#[cfg(test)]
#[allow(clippy::indexing_slicing, reason = "test code, not the untrusted-input surface the lint protects")]
mod tests {
    use super::*;

    #[test]
    fn has_exactly_120_entries_matching_the_spec_count() {
        assert_eq!(DISTANCE_MAP.len(), 120);
    }

    #[test]
    fn first_and_last_entries_match_the_spec_text() {
        assert_eq!(DISTANCE_MAP[0], (0, 1));
        assert_eq!(DISTANCE_MAP[119], (8, 7));
    }
}
