#[cfg(test)]
mod tests {
    use vaco_codec_vlc::{is_prefix_free, kraft_numerator};

    use super::{
        F_HUFFMAN_ENV_1_5DB, F_HUFFMAN_ENV_3_0DB, F_HUFFMAN_ENV_BAL_1_5DB, F_HUFFMAN_ENV_BAL_3_0DB,
        T_HUFFMAN_ENV_1_5DB, T_HUFFMAN_ENV_3_0DB, T_HUFFMAN_ENV_BAL_1_5DB, T_HUFFMAN_ENV_BAL_3_0DB,
        T_HUFFMAN_NOISE_3_0DB, T_HUFFMAN_NOISE_BAL_3_0DB,
    };

    #[test]
    fn every_sbr_huffman_table_is_prefix_free_and_complete() {
        let tables: &[(&str, &[vaco_codec_vlc::VlcEntry])] = &[
            ("t_huffman_env_1_5dB", &T_HUFFMAN_ENV_1_5DB),
            ("f_huffman_env_1_5dB", &F_HUFFMAN_ENV_1_5DB),
            ("t_huffman_env_bal_1_5dB", &T_HUFFMAN_ENV_BAL_1_5DB),
            ("f_huffman_env_bal_1_5dB", &F_HUFFMAN_ENV_BAL_1_5DB),
            ("t_huffman_env_3_0dB", &T_HUFFMAN_ENV_3_0DB),
            ("f_huffman_env_3_0dB", &F_HUFFMAN_ENV_3_0DB),
            ("t_huffman_env_bal_3_0dB", &T_HUFFMAN_ENV_BAL_3_0DB),
            ("f_huffman_env_bal_3_0dB", &F_HUFFMAN_ENV_BAL_3_0DB),
            ("t_huffman_noise_3_0dB", &T_HUFFMAN_NOISE_3_0DB),
            ("t_huffman_noise_bal_3_0dB", &T_HUFFMAN_NOISE_BAL_3_0DB),
        ];
        for (name, table) in tables {
            assert!(is_prefix_free(table), "{name} is not prefix-free");
            let max_len = table.iter().map(|e| e.len).max().unwrap_or(0);
            let expected = 1u64 << max_len;
            assert_eq!(
                kraft_numerator(table, max_len),
                expected,
                "{name} is not a complete code"
            );
        }
    }

    #[test]
    fn every_table_has_exactly_two_lav_plus_one_entries_symbols_dense_from_zero() {
        let tables: &[(&str, &[vaco_codec_vlc::VlcEntry])] = &[
            ("t_huffman_env_1_5dB", &T_HUFFMAN_ENV_1_5DB),
            ("f_huffman_env_1_5dB", &F_HUFFMAN_ENV_1_5DB),
            ("t_huffman_env_bal_1_5dB", &T_HUFFMAN_ENV_BAL_1_5DB),
            ("f_huffman_env_bal_1_5dB", &F_HUFFMAN_ENV_BAL_1_5DB),
            ("t_huffman_env_3_0dB", &T_HUFFMAN_ENV_3_0DB),
            ("f_huffman_env_3_0dB", &F_HUFFMAN_ENV_3_0DB),
            ("t_huffman_env_bal_3_0dB", &T_HUFFMAN_ENV_BAL_3_0DB),
            ("f_huffman_env_bal_3_0dB", &F_HUFFMAN_ENV_BAL_3_0DB),
            ("t_huffman_noise_3_0dB", &T_HUFFMAN_NOISE_3_0DB),
            ("t_huffman_noise_bal_3_0dB", &T_HUFFMAN_NOISE_BAL_3_0DB),
        ];
        for (name, table) in tables {
            assert_eq!(table.len() % 2, 1, "{name} should have an odd (2*LAV+1) entry count");
            let mut symbols: Vec<u32> = table.iter().map(|e| e.symbol).collect();
            symbols.sort_unstable();
            let expected: Vec<u32> = (0..table.len() as u32).collect();
            assert_eq!(symbols, expected, "{name}'s symbols should be dense from 0");
        }
    }
}
