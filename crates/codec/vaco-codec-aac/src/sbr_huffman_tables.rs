//! SBR Huffman tables (ISO/IEC 14496-3 subpart 4 Annex 4.A.6.1, Tables
//! 4.A.79-4.A.88): envelope and noise-floor scalefactor entropy coding.
//!
//! Ten distinct tables, transcribed directly from the primary text (each
//! entry's `(index, length, codeword)` triple, in hexadecimal, exactly as
//! printed) rather than recalled -- the same discipline this crate already
//! held its AAC-LC spectral codebooks to in `spectral_tables.rs`. Table
//! 4.A.78's own overview names twelve table symbols, but two
//! (`f_huffman_noise_3_0dB`, `f_huffman_noise_bal_3_0dB`) are declared
//! identical to `f_huffman_env_3_0dB`/`f_huffman_env_bal_3_0dB`
//! respectively (its own Note 2) -- `sbr.rs` reuses those two constants
//! directly rather than this module carrying two duplicate arrays.
//!
//! Every table's `symbol` field is the raw table index (`0..=2*LAV`); the
//! decoded envelope/noise value is that index minus the table's own LAV
//! (largest absolute value, named in each constant's own doc comment,
//! and recoverable at any point as `(table.len() - 1) / 2`), per
//! Sec 4.A.6.1's own definition of `sbr_huff_dec()`.
//!
//! Verified, not just transcribed: every table below independently passes
//! `vaco_codec_vlc::is_prefix_free` and a Kraft-sum completeness check
//! (`kraft_numerator(entries, max_len) == 1 << max_len`) in this module's
//! own tests -- the same net #444 held AAC's spectral codebooks to, and
//! (worth recording) all ten of these passed on the first transcription,
//! unlike the QMF window table in `qmf.rs` whose extraction needed a
//! symmetry cross-check to catch two flipped signs.

#![allow(
    dead_code,
    reason = "landed as verified building blocks (each independently prefix-free and \
              complete, see this module's own tests) ahead of sbr_data()'s envelope/noise \
              bitstream parsing, which was not attempted this pass -- see qmf.rs's own doc \
              for why (a broadband QMF defect that would make decoding this data pointless \
              until found)"
)]

