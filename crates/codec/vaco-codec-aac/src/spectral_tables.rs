/// The Huffman table for spectral codebook `hcb` (1..=11), or `None` for 0
/// (`ZERO_HCB`, no table — every coefficient in the band is zero) and for
/// anything outside the valid range (12 is reserved; 13/14/15 are
/// noise/intensity markers with no spectral table of their own).
pub(crate) fn spectrum_table(hcb: u8) -> Option<&'static [VlcEntry]> {
    Some(match hcb {
        1 => &SPECTRUM_HCB_1,
        2 => &SPECTRUM_HCB_2,
        3 => &SPECTRUM_HCB_3,
        4 => &SPECTRUM_HCB_4,
        5 => &SPECTRUM_HCB_5,
        6 => &SPECTRUM_HCB_6,
        7 => &SPECTRUM_HCB_7,
        8 => &SPECTRUM_HCB_8,
        9 => &SPECTRUM_HCB_9,
        10 => &SPECTRUM_HCB_10,
        11 => &SPECTRUM_HCB_11,
        _ => return None,
    })
}

#[cfg(test)]
mod tests {
    #![allow(
        clippy::unwrap_used,
        clippy::indexing_slicing,
        clippy::panic,
        reason = "test code"
    )]
    use super::{CODEBOOK_INFO, SCALEFACTOR_HUFFMAN, spectrum_table};
    use vaco_codec_vlc::{is_prefix_free, kraft_numerator};

    /// Every codebook's entry count must equal the size its own (unsigned,
    /// dim, lav) parameters predict via the spec's `mod`/`off` formula
    /// (`mod = unsigned ? lav+1 : 2*lav+1`, size = `mod^dim`) — this is an
    /// exact integer identity, not a plausibility check, and a transcription
    /// that dropped or duplicated even one entry fails it. Combined with
    /// `is_prefix_free`/`kraft_numerator` (Kraft-complete at each table's own
    /// longest codeword), this is the same two-part transcription check this
    /// workspace already holds MP3's and now this crate's own tables to.
    #[test]
    fn every_codebook_is_the_right_size_and_a_complete_prefix_free_code() {
        for hcb in 1u8..=11 {
            let info = CODEBOOK_INFO[usize::from(hcb)];
            let modulus = if info.unsigned {
                u32::from(info.lav) + 1
            } else {
                2 * u32::from(info.lav) + 1
            };
            let expected_size = modulus.pow(u32::from(info.dim));
            let table = spectrum_table(hcb).unwrap_or_else(|| panic!("hcb {hcb} missing"));
            assert_eq!(
                table.len() as u32,
                expected_size,
                "hcb {hcb}: table has {} entries, formula predicts {expected_size}",
                table.len()
            );
            assert!(is_prefix_free(table), "hcb {hcb} is not prefix-free");
            let max_len = table.iter().map(|e| e.len).max().unwrap_or(0);
            assert_eq!(
                kraft_numerator(table, max_len),
                1u64 << max_len,
                "hcb {hcb} is not a complete code"
            );
        }
    }

    #[test]
    fn the_scalefactor_codebook_is_121_entries_complete_and_prefix_free() {
        assert_eq!(SCALEFACTOR_HUFFMAN.len(), 121);
        assert!(is_prefix_free(&SCALEFACTOR_HUFFMAN));
        let max_len = SCALEFACTOR_HUFFMAN.iter().map(|e| e.len).max().unwrap_or(0);
        assert_eq!(
            kraft_numerator(&SCALEFACTOR_HUFFMAN, max_len),
            1u64 << max_len
        );
    }

    #[test]
    fn hcb_0_and_12_and_above_have_no_spectral_table() {
        assert!(spectrum_table(0).is_none());
        assert!(spectrum_table(12).is_none());
        assert!(spectrum_table(13).is_none());
    }
}
